#!/bin/bash
# Generates every app icon from branding/koalino.svg (#165): the Android launcher (legacy and
# adaptive), the Windows .ico, the macOS app icon set, the Linux window and packaging icons, the
# browser extension's icons, the server web UI's favicon, the Teams app's icons and the F-Droid
# listing icon. Rerun it after changing the SVG and commit the results.
#
# Usage: branding/make-icons.sh   (from anywhere; needs rsvg-convert and ImageMagick's `magick`)
# Side effects: overwrites the generated icon files listed below; writes temporary files in a
# private folder that is removed on exit.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
source_svg="$repo/branding/koalino.svg"
background_colour="#571775" # the purple square behind the koala, also the adaptive background
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# The koala alone, without its purple square, for the adaptive foreground and the outline icons.
grep -q "fill=\"$background_colour\"" "$source_svg"
sed "/<rect [^>]*fill=\"$background_colour\"/d" "$source_svg" >"$work/koala.svg"
rsvg-convert -w 2048 -h 2048 "$work/koala.svg" -o "$work/koala-large.png"
magick "$work/koala-large.png" -trim +repage "$work/koala-trimmed.png"

# full_icon SIZE OUT: the whole icon (purple square and koala) as a SIZE×SIZE PNG.
full_icon() { rsvg-convert -w "$1" -h "$1" "$source_svg" -o "$2"; }

# inset_icon SIZE CONTENT OUT: the whole icon drawn CONTENT pixels wide, centred on a transparent
# SIZE×SIZE canvas (macOS draws icons inside a margin, unlike the other platforms).
inset_icon() {
  rsvg-convert -w "$2" -h "$2" "$source_svg" -o "$work/inset.png"
  magick "$work/inset.png" -background none -gravity center -extent "$1x$1" "$3"
}

# --- Android: the legacy launcher icon and the adaptive icon (API 26+). ---
android_res="$repo/ui/android/app/src/main/res"
for pair in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  density=${pair%%:*}
  scale=${pair##*:}
  launcher=$(python3 -c "print(round(48 * $scale))")
  canvas=$(python3 -c "print(round(108 * $scale))")
  # The koala fills 56 of the adaptive icon's 108 dp, so its ears stay inside a circular mask.
  koala=$(python3 -c "print(round(56 * $scale))")
  mkdir -p "$android_res/mipmap-$density"
  full_icon "$launcher" "$android_res/mipmap-$density/ic_launcher.png"
  magick "$work/koala-trimmed.png" -resize "${koala}x${koala}" -background none -gravity center \
    -extent "${canvas}x${canvas}" "$android_res/mipmap-$density/ic_launcher_foreground.png"
done
mkdir -p "$android_res/mipmap-anydpi-v26"
cat >"$android_res/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/make-icons.sh (#165): Koalino's adaptive launcher icon. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
XML
cat >"$android_res/values/ic_launcher_background.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/make-icons.sh (#165): the adaptive icon's background colour. -->
<resources>
    <color name="ic_launcher_background">$background_colour</color>
</resources>
XML

# --- Windows: one .ico holding the sizes Explorer and the taskbar ask for. ---
for size in 16 24 32 48 64 128 256; do full_icon "$size" "$work/win-$size.png"; done
magick "$work"/win-{16,24,32,48,64,128,256}.png "$repo/ui/windows/runner/resources/app_icon.ico"

# --- macOS: Apple's grid draws the icon 824 of 1024 pixels wide. ---
mac="$repo/ui/macos/Runner/Assets.xcassets/AppIcon.appiconset"
for size in 16 32 64 128 256 512 1024; do
  inset_icon "$size" "$(python3 -c "print(round($size * 824 / 1024))")" "$mac/app_icon_$size.png"
done

# --- Linux: the window icon the runner loads, and the icons the packages install. ---
full_icon 256 "$repo/ui/linux/runner/resources/koalino.png"
mkdir -p "$repo/tools/packaging/linux"
full_icon 128 "$repo/tools/packaging/linux/koalino-128.png"
full_icon 192 "$repo/tools/packaging/linux/koalino-192.png"
cp "$source_svg" "$repo/tools/packaging/linux/koalino.svg"

# --- Browser extension. ---
for size in 16 32 48 128; do full_icon "$size" "$repo/browser-extension/static/icon-$size.png"; done

# --- Server web UI: Next.js serves app/icon.svg as the favicon. Project website (#166). ---
cp "$source_svg" "$repo/web/app/icon.svg"
cp "$source_svg" "$repo/site/koalino.svg"

# --- Teams app: a 192 px colour icon and a 32 px white outline on transparency: the koala's dark
# lines in white, its light fill transparent (the dark shape is a silhouette under the fill, so the
# lines come from the rendered koala's dark pixels). ---
full_icon 192 "$repo/teams-bot/deploy/teams-app/color.png"
magick "$work/koala-trimmed.png" \( +clone -alpha off -colorspace gray -negate \) \
  \( -clone 0 -alpha extract \) -delete 0 -compose multiply -composite "$work/lines-mask.png"
magick "$work/lines-mask.png" -background white -alpha shape -resize 30x30 -background none \
  -gravity center -extent 32x32 "$repo/teams-bot/deploy/teams-app/outline.png"

# --- F-Droid and store listings (#163, #127): a 512 px icon. ---
listing="$repo/fastlane/metadata/android/en-US/images"
mkdir -p "$listing"
full_icon 512 "$listing/icon.png"

echo "icons generated from $source_svg"
