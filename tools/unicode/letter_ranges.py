"""Writes the Unicode letter (\\p{L}) ranges that the NPU tokenizer uses for GPT-2's word split.

Rust's standard library has no general-category lookup, and `char::is_alphabetic` also counts
combining vowel signs (Thai, Devanagari, Arabic...), which GPT-2's split keeps apart from letters.
This script writes `core/adapters/ai/npu_whisper/unicode_letters.rs` from Python's `unicodedata`.

Usage: python3 -I tools/unicode/letter_ranges.py > core/adapters/ai/npu_whisper/unicode_letters.rs
"""
import sys
import unicodedata


def letter_ranges():
    """Returns the inclusive (first, last) code point ranges whose category starts with L."""
    ranges = []
    start = None
    for code in range(sys.maxunicode + 2):
        is_letter = code <= sys.maxunicode and unicodedata.category(chr(code)).startswith("L")
        if is_letter and start is None:
            start = code
        elif not is_letter and start is not None:
            ranges.append((start, code - 1))
            start = None
    return ranges


def main():
    """Prints the Rust module to standard output."""
    ranges = letter_ranges()
    print(f"""// Unicode letters (general category L*), for GPT-2's word split in the NPU tokenizer (#75).
// Generated by tools/unicode/letter_ranges.py from Unicode {unicodedata.unidata_version}; do not edit by hand.

/// Inclusive code point ranges of the letters, sorted.
const LETTER_RANGES: &[(u32, u32)] = &[""")
    for first, last in ranges:
        print(f"    (0x{first:04X}, 0x{last:04X}),")
    print("""];

/// Reports whether a character is a Unicode letter (`\\p{L}`), as GPT-2's pattern means it.
///
/// Inputs: The character. Outputs: True for categories Lu, Ll, Lt, Lm and Lo; false for marks,
/// digits and everything else. Side effects: None.
pub(super) fn is_letter(character: char) -> bool {
    let code = u32::from(character);
    LETTER_RANGES
        .binary_search_by(|(first, last)| {
            if code < *first {
                std::cmp::Ordering::Greater
            } else if code > *last {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}""")


if __name__ == "__main__":
    main()
